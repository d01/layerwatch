package app.layerwatch.protocol.job

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNotNull
import org.junit.Assert.assertTrue
import org.junit.Assume.assumeTrue
import org.junit.Test
import java.io.File
import java.io.StringReader

/**
 * Against a real job from the X1C (vent_blade, OrcaSlicer 2.4.2). Expected values were
 * extracted independently with a Python script, not from this parser.
 */
class JobArchiveTest {
    private fun fixture(): File = File.createTempFile("job", ".3mf").apply {
        deleteOnExit()
        outputStream().use { out -> checkNotNull(JobArchiveTest::class.java.getResourceAsStream("/jobs/bleed_rest.gcode.3mf")).use { it.copyTo(out) } }
    }

    @Test fun sliceInfo() {
        val s = JobArchive.read(fixture(), withGcode = false).slice!!
        assertEquals("OrcaSlicer 2.4.2", s.slicer)
        assertEquals(735, s.predictionSec)
        assertEquals(3.71, s.weightG!!, 1e-9)
        val f = s.filaments.single()
        assertEquals(3, f.id)
        assertEquals("PETG", f.type)
        assertEquals("#000000", f.colorHex)
        assertEquals(1.23, f.usedM!!, 1e-9)
        assertEquals(SliceObject(270, "vent_blade.stl", false), s.objects.single())
    }

    @Test fun plateSettingsAndImages() {
        val job = JobArchive.read(fixture(), withGcode = false)
        val obj = job.plateInfo!!.objects.single()
        assertEquals("vent_blade.stl", obj.name)
        assertEquals(754.888, obj.areaMm2!!, 1e-3)
        val st = job.settings!!
        assertEquals(0.4, st.layerHeight!!, 1e-9)
        assertEquals(2, st.wallLoops)
        assertEquals("15%", st.infillDensity)
        assertEquals("crosshatch", st.infillPattern)
        assertEquals("0.40mm Standard @BBL X1C 0.8 nozzle", st.printProfile)
        assertEquals(255.0, st.nozzleTemp(2)!!, 0.0)
        assertEquals(70.0, st.bedTemp(2)!!, 0.0) // textured plate
        assertNotNull(job.plateImage)
        assertNotNull(job.topImage)
        assertNotNull(job.pickImage)
    }

    @Test fun gcodeLayersFeaturesAndExtrusion() {
        val g = JobArchive.read(fixture()).gcode!!
        assertEquals("OrcaSlicer 2.4.2", g.header.generator)
        assertEquals(12 * 60 + 15, g.header.totalEstimatedSec)
        assertEquals(17, g.header.totalLayers)
        assertEquals(17, g.layers.size)
        assertEquals(0.4f, g.layers.first().z, 1e-4f)
        assertEquals(6.8f, g.layers.last().z, 1e-4f)
        assertEquals((1..17).toList(), g.layers.map { it.number })
        assertEquals(2, g.initialTool) // M620 S2A: slicer filament 3
        assertTrue(g.toolChanges.isEmpty())
        assertEquals(1029.74f, g.layers.sumOf { it.extrudedMm.toDouble() }.toFloat(), 0.05f) // incl. 134 arc moves
        val all = g.layers.flatMap { it.features }.toSet()
        assertTrue(Feature.OuterWall in all && Feature.Bridge in all && Feature.TopSurface in all && Feature.GapFill in all)
        // Paths are contiguous per layer and every path has at least a segment.
        for (l in g.layers) for (p in l.firstPath until l.firstPath + l.pathCount) {
            assertEquals(l.number, g.pathLayer[p])
            assertTrue(g.pathPoints(p).count() >= 2)
        }
        assertTrue(g.bounds[0] > 100f && g.bounds[2] < 155f) // matches plate bbox ~104..151
    }

    @Test fun parserHandlesMarkersToolChangesAndAbsoluteE() {
        val gcode = """
            ; generated by TestSlicer 1.0 on today
            ; total estimated time: 1h 2m 3s
            M82
            G92 E0
            M620 S0A
            T0
            ; Z_HEIGHT: 0.2
            ; layer num/total_layer_count: 1/2
            ; FEATURE: Outer wall
            G1 X0 Y0
            G1 X10 Y0 E1.0
            G1 X10 Y10 E2.0
            ; FEATURE: Sparse infill
            G1 X0 Y10 E3.0
            M73 P50 R7
            M620 S1A
            T1
            M73 L2
            ; Z_HEIGHT: 0.4
            G1 X0 Y0 E4.5
        """.trimIndent()
        val g = GcodeParser.parse(StringReader(gcode).buffered())
        assertEquals(3723, g.header.totalEstimatedSec)
        assertEquals(listOf(1, 2), g.layers.map { it.number })
        assertEquals(0.4f, g.layers[1].z, 1e-6f) // height comment after the M73 L marker
        assertEquals(7, g.layers[1].plannedRemainingMin)
        assertEquals(listOf(ToolChange(layer = 1, fromTool = 0, toTool = 1)), g.toolChanges)
        assertEquals(3.0f, g.layers[0].extrudedMmByTool[0]!!, 1e-6f) // absolute E deltas
        assertEquals(1.5f, g.layers[1].extrudedMmByTool[1]!!, 1e-6f)
        assertEquals(setOf(Feature.OuterWall, Feature.SparseInfill), g.layers[0].features)
        assertEquals(3, g.pathCount) // wall, infill (feature change), layer-2 move
    }

    @Test fun arcsAreInterpolated() {
        val g = GcodeParser.parse(
            StringReader(
                """
                M83
                ; layer num/total_layer_count: 1/1
                ; FEATURE: Outer wall
                G1 X10 Y0
                G3 X-10 Y0 I-10 J0 E5
                """.trimIndent()
            ).buffered()
        )
        // A counter-clockwise half circle of radius 10 (~31 mm) becomes ~31 segments, all on the circle.
        val pts = g.pathPoints(0)
        assertTrue(pts.count() in 25..40)
        for (k in pts) {
            val r = kotlin.math.hypot(g.points[k * 2], g.points[k * 2 + 1])
            assertEquals(10f, r, 1e-3f)
        }
        assertTrue(pts.map { g.points[it * 2 + 1] }.all { it >= -1e-3f }) // went through +Y (CCW)
    }

    @Test fun platesAndHeaderLayersWithoutParsing() {
        val f = fixture()
        // A file sent from the slicer carries only the plate being printed.
        assertEquals(listOf(1), JobArchive.plates(f))
        assertEquals(17, JobArchive.headerLayers(f, 1))
        assertEquals(null, JobArchive.headerLayers(f, 2))
    }

    @Test fun pickMaskDecoding() = assertEquals(373, JobFile.pickObjectId(117, 1, 0))

    /** A large real job (22 MB of G-code), when BAMBU_BIG_JOB points at one; not committed. */
    @Test fun largeRealJob() {
        val f = File(System.getenv("BAMBU_BIG_JOB") ?: "/nonexistent")
        assumeTrue(f.exists())
        val t0 = System.nanoTime()
        val g = JobArchive.read(f).gcode!!
        println("BIG: parsed ${g.layers.size} layers, ${g.pathCount} paths, ${g.pointCount} points in ${(System.nanoTime() - t0) / 1_000_000} ms")
        assertEquals(502, g.layers.size)
        assertEquals(108.8f, g.layer(272)!!.z, 1e-3f) // 272 × 0.4 mm; the height comment precedes its layer marker
        assertEquals(324, g.lastLayerWith(Feature.OverhangWall)!!.number)
        assertEquals(297, g.nextLayerWith(Feature.InternalSolidInfill, after = 272)!!.number)
        assertEquals(83, g.layer(272)!!.plannedRemainingMin)
    }
}
