package app.layerwatch.protocol.job

import java.io.BufferedReader

/**
 * Streams G-code into a [GcodeModel]. Understands what OrcaSlicer and Bambu Studio emit:
 * `; layer num/total_layer_count:`, `M73 L` and `;LAYER_CHANGE` for layers, `; Z_HEIGHT:`
 * / `;Z:` for heights, `; FEATURE:` / `;TYPE:` for features, `M73 P R` for the slicer's
 * time plan, `M620 S<n>A` / `T<n>` for filament changes, M82/M83/G92 for extrusion mode.
 * Arcs (G2/G3 with I/J, emitted when arc fitting is on) are interpolated into ~1 mm
 * segments so curved walls stay curved.
 */
object GcodeParser {
    private const val ARC_SEGMENT_MM = 1f

    fun parse(reader: BufferedReader): GcodeModel = State().apply {
        reader.lineSequence().forEach(::line)
    }.finish()

    private class State {
        // header
        var generator: String? = null
        var totalSec: Int? = null
        var modelSec: Int? = null
        var headerLayers: Int? = null
        var maxZ: Float? = null

        // machine state
        var x = 0f
        var y = 0f
        var relativeE = true
        var lastE = 0f
        var feature = Feature.Other
        var tool: Int? = null
        var initialTool: Int? = null
        var pendingZ = 0f
        var lastRemaining: Int? = null

        // layers
        val layers = ArrayList<GcodeLayer>()
        var layerNumber = 0
        var layerZ = 0f
        var layerFirstPath = 0
        var layerRemaining: Int? = null
        var layerExtruded = HashMap<Int, Float>()
        var layerFeatures = HashSet<Feature>()
        val toolChanges = ArrayList<ToolChange>()

        // paths
        var points = FloatArray(1 shl 16)
        var pointCount = 0
        var pathStart = IntArray(1 shl 12)
        var pathLayer = IntArray(1 shl 12)
        var pathFeature = ByteArray(1 shl 12)
        var pathCount = 0
        var inPath = false
        val bounds = floatArrayOf(Float.MAX_VALUE, Float.MAX_VALUE, -Float.MAX_VALUE, -Float.MAX_VALUE)

        fun line(raw: String) {
            if (raw.isEmpty()) return
            if (raw[0] == ';') return comment(raw)
            val code = raw.substringBefore(';').trim()
            if (code.isEmpty()) return
            when {
                code.startsWith("G1 ") || code.startsWith("G0 ") || code.startsWith("G2 ") || code.startsWith("G3 ") -> move(code)
                code.startsWith("M73 ") -> m73(code)
                code == "M83" -> relativeE = true
                code == "M82" -> relativeE = false
                code.startsWith("G92") -> param(code, 'E')?.let { lastE = it }
                code.startsWith("M620 S") -> m620(code)
                code.length in 2..3 && code[0] == 'T' -> code.substring(1).toIntOrNull()?.let(::toolChange)
            }
        }

        private fun comment(c: String) {
            when {
                c.startsWith("; FEATURE:") -> changeFeature(Feature.parse(c.substringAfter(':')))
                c.startsWith(";TYPE:") -> changeFeature(Feature.parse(c.substringAfter(':')))
                c.startsWith("; Z_HEIGHT:") -> c.substringAfter(':').trim().toFloatOrNull()?.let(::height)
                c.startsWith(";Z:") -> c.substringAfter(':').trim().toFloatOrNull()?.let(::height)
                c.startsWith("; layer num/total_layer_count:") ->
                    c.substringAfter(':').substringBefore('/').trim().toIntOrNull()?.let(::startLayer)
                c.startsWith(";LAYER_CHANGE") -> startLayer(layerNumber + 1)
                c.startsWith("; generated by ") -> generator = c.removePrefix("; generated by ").substringBefore(" on ").trim()
                c.startsWith("; total estimated time:") -> totalSec = duration(c.substringAfter(':'))
                // Orca/Bambu put both on one line: "; model printing time: 4m 42s; total estimated time: 12m 15s"
                c.startsWith("; model printing time:") -> {
                    modelSec = duration(c.substringAfter(':').substringBefore(';'))
                    if ("total estimated time:" in c) totalSec = duration(c.substringAfter("total estimated time:"))
                }
                c.startsWith("; total layer number:") -> headerLayers = c.substringAfter(':').trim().toIntOrNull()
                c.startsWith("; max_z_height:") -> maxZ = c.substringAfter(':').trim().toFloatOrNull()
            }
        }

        /** A height comment may follow the layer marker; it belongs to that layer until it prints. */
        private fun height(z: Float) {
            pendingZ = z
            if (layerNumber > 0 && pathCount == layerFirstPath) layerZ = z
        }

        private fun changeFeature(f: Feature) {
            if (f != feature) endPath()
            feature = f
        }

        private fun m73(code: String) {
            param(code, 'R')?.let { lastRemaining = it.toInt() }
            // Bambu firmware layer marker; Orca also emits its own layer comments, so only
            // advance if this is a new layer.
            param(code, 'L')?.toInt()?.let { if (it > layerNumber) startLayer(it) }
        }

        private fun m620(code: String) {
            // "M620 S<n>A" starts an AMS swap to slot n; S255 means unload.
            val n = code.removePrefix("M620 S").takeWhile { it.isDigit() }.toIntOrNull() ?: return
            if (n in 0..15) toolChange(n)
        }

        private fun toolChange(t: Int) {
            if (t !in 0..15 || t == tool) return
            if (layerNumber == 0) {
                initialTool = t
            } else {
                endPath()
                toolChanges += ToolChange(layerNumber, tool, t)
            }
            tool = t
        }

        private fun startLayer(n: Int) {
            if (n == layerNumber) return
            closeLayer()
            layerNumber = n
            layerZ = pendingZ
            layerFirstPath = pathCount
            layerRemaining = lastRemaining
        }

        private fun closeLayer() {
            endPath()
            if (layerNumber <= 0) return
            layers += GcodeLayer(
                number = layerNumber, z = layerZ, firstPath = layerFirstPath, pathCount = pathCount - layerFirstPath,
                plannedRemainingMin = layerRemaining, extrudedMmByTool = layerExtruded, features = layerFeatures,
            )
            layerExtruded = HashMap()
            layerFeatures = HashSet()
        }

        private fun move(code: String) {
            var nx = x
            var ny = y
            var e: Float? = null
            var ci: Float? = null
            var cj: Float? = null
            var i = 3
            val n = code.length
            while (i < n) {
                val k = code[i]
                if (k == 'X' || k == 'Y' || k == 'E' || k == 'I' || k == 'J') {
                    var j = i + 1
                    while (j < n && code[j] != ' ') j++
                    val v = code.substring(i + 1, j).toFloatOrNull()
                    if (v != null) when (k) {
                        'X' -> nx = v
                        'Y' -> ny = v
                        'E' -> e = v
                        'I' -> ci = v
                        else -> cj = v
                    }
                    i = j
                } else {
                    i++
                }
            }
            val arc = (code[1] == '2' || code[1] == '3') && (ci != null || cj != null)
            val de = when {
                e == null -> 0f
                relativeE -> e
                else -> (e - lastE).also { lastE = e }
            }
            val moved = nx != x || ny != y
            if (de > 0f && moved && layerNumber > 0) {
                if (!inPath) beginPath()
                if (arc) arcPoints(nx, ny, x + (ci ?: 0f), y + (cj ?: 0f), clockwise = code[1] == '2')
                addPoint(nx, ny)
                val t = tool ?: initialTool ?: 0
                layerExtruded[t] = (layerExtruded[t] ?: 0f) + de
                layerFeatures += feature
            } else if (moved) {
                endPath()
            }
            x = nx
            y = ny
        }

        /** Intermediate points of an arc from the current position to (ex, ey) around (cx, cy). */
        private fun arcPoints(ex: Float, ey: Float, cx: Float, cy: Float, clockwise: Boolean) {
            val r = kotlin.math.hypot(x - cx, y - cy)
            if (r < 1e-3f) return
            val a0 = kotlin.math.atan2(y - cy, x - cx)
            var sweep = kotlin.math.atan2(ey - cy, ex - cx) - a0
            val twoPi = (2 * Math.PI).toFloat()
            if (clockwise) { if (sweep >= 0f) sweep -= twoPi } else { if (sweep <= 0f) sweep += twoPi }
            val steps = (kotlin.math.abs(sweep) * r / ARC_SEGMENT_MM).toInt().coerceIn(1, 128)
            for (s in 1 until steps) {
                val a = a0 + sweep * s / steps
                addPoint(cx + r * kotlin.math.cos(a), cy + r * kotlin.math.sin(a))
            }
        }

        private fun beginPath() {
            if (pathCount == pathStart.size) {
                pathStart = pathStart.copyOf(pathCount * 2)
                pathLayer = pathLayer.copyOf(pathCount * 2)
                pathFeature = pathFeature.copyOf(pathCount * 2)
            }
            pathStart[pathCount] = pointCount
            pathLayer[pathCount] = layerNumber
            pathFeature[pathCount] = feature.ordinal.toByte()
            pathCount++
            inPath = true
            addPoint(x, y)
        }

        private fun endPath() {
            inPath = false
        }

        private fun addPoint(px: Float, py: Float) {
            if (pointCount * 2 + 2 > points.size) points = points.copyOf(points.size * 2)
            points[pointCount * 2] = px
            points[pointCount * 2 + 1] = py
            pointCount++
            if (px < bounds[0]) bounds[0] = px
            if (py < bounds[1]) bounds[1] = py
            if (px > bounds[2]) bounds[2] = px
            if (py > bounds[3]) bounds[3] = py
        }

        fun finish(): GcodeModel {
            closeLayer()
            return GcodeModel(
                header = GcodeHeader(generator, totalSec, modelSec, headerLayers, maxZ),
                layers = layers,
                points = points, pointCount = pointCount,
                pathStart = pathStart, pathLayer = pathLayer, pathFeature = pathFeature, pathCount = pathCount,
                toolChanges = toolChanges,
                bounds = bounds,
                initialTool = initialTool,
            )
        }

        private fun param(code: String, key: Char): Float? {
            val i = code.indexOf(" $key")
            if (i < 0) return null
            var j = i + 2
            while (j < code.length && code[j] != ' ') j++
            return code.substring(i + 2, j).toFloatOrNull()
        }

        /** "4h 22m 15s", "12m 15s", "1d 2h 3m 4s" -> seconds. */
        private fun duration(s: String): Int? {
            var total = 0
            var any = false
            Regex("""(\d+)\s*([dhms])""").findAll(s).forEach {
                any = true
                val v = it.groupValues[1].toInt()
                total += when (it.groupValues[2]) { "d" -> v * 86400; "h" -> v * 3600; "m" -> v * 60; else -> v }
            }
            return total.takeIf { any }
        }
    }
}
